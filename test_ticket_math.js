const assert=require('node:assert/strict'),math=require('./ticket_math.js');
const make=(odds,id,line='62.5')=>({odds,game_id:id,market:'Receiving Yards',line,side:'MORE',player:'Synthetic '+id});
const legs=[make('-200','a'),make('-115','b'),make('-110','c')];
const ticket=math.analyze(legs,'10');
assert.equal(ticket.payout,53.54);assert.ok(Math.abs(ticket.profit-43.54)<1e-10);
assert.equal(math.american(ticket.combined.decimal),'+435');
assert.equal(ticket.true_probability,null);assert.equal(ticket.market_probability,null);assert.equal(ticket.fair_payout,null);
assert.equal(math.payout('1',math.price('1.915')),1.92);
assert.equal(math.payout('11',math.price('-110')),21);
assert.throws(()=>math.cents('1.005'));assert.throws(()=>math.cents('-10'));
for(const odds of ['','0','1','-99','+99','abc','Infinity'])assert.throws(()=>math.price(odds));
const observed=[{...make('-110','a'),opposite_odds:'-110'},{...make('-110','b'),opposite_odds:'-110'}];
const estimate=math.analyze(observed,'10');
assert.equal(estimate.market_probability,.25);assert.equal(estimate.true_probability,null);
assert.equal(estimate.fair_payout,40);assert.equal(estimate.fair_odds,4);
assert.ok(Math.abs(estimate.expected+0.8875)<1e-9);
const cover=math.cover(observed,'10');
assert.equal(cover.eligible,true);assert.equal(cover.count,4);assert.equal(cover.total,40);
assert.ok(Math.abs(cover.combinations.reduce((p,c)=>p+c.probability,0)-1)<1e-12);
assert.ok(cover.combinations.every(c=>c.net<0));assert.ok(cover.expected<0);
assert.equal(math.cover(observed.map(l=>({...l,game_id:'same'})),'10').eligible,false);
assert.equal(math.analyze(observed.map(l=>({...l,game_id:'same'})),'10','4').market_probability,null);
assert.equal(math.cover(observed.map(l=>({...l,opposite_odds:''})),'10').eligible,false);
assert.equal(math.cover(observed.map(l=>({...l,line:'62'})),'10').eligible,false);
assert.equal(math.cover(observed.map(l=>({...l,market:'3-way Moneyline'})),'10').eligible,false);
assert.equal(math.cover(Array.from({length:7},(_,i)=>({...observed[0],game_id:String(i)})),'10').eligible,false);
console.log('PASS: exact combined odds/payout/profit, 3-leg example, cent rounding, missing true probability, de-vig benchmark, cover combinations/cost/net, correlation/push/third-outcome guards');
